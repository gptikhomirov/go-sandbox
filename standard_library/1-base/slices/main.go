/*
Пакет slices — удобные действия над срезами (списками).

Срез (slice) — это список значений: []int{5, 2, 9}. Раньше для поиска или сортировки
приходилось писать цикл вручную. Пакет slices даёт готовые функции: найти, проверить, отсортировать.

Важная ловушка про срезы: если написать b := a, то b и a будут указывать на ОДИН и тот же
список. Изменишь b — изменится и a. Чтобы получить НЕЗАВИСИМУЮ копию, есть slices.Clone.

Как запустить:  go run main.go
*/
package main

import (
	"fmt"
	"slices"
)

func main() {
	nums := []int{5, 2, 9, 1}

	// Contains — есть ли значение в списке (отвечает true/false). Index — на каком месте (номер).
	fmt.Println(slices.Contains(nums, 9)) // => true
	fmt.Println(slices.Index(nums, 9))    // => 2  (нумерация с 0: 5=0, 2=1, 9=2)

	// Sort сортирует список по возрастанию (меняет сам список). Короче, чем sort.Ints.
	slices.Sort(nums)
	fmt.Println(nums) // => [1 2 5 9]

	// Max и Min — самый большой и самый маленький элементы.
	fmt.Println(slices.Max(nums), slices.Min(nums)) // => 9 1

	// Clone делает НЕЗАВИСИМУЮ копию. Меняем копию — оригинал не трогается.
	original := []int{1, 2, 3}
	cloned := slices.Clone(original)
	cloned[0] = 100
	fmt.Println(original, cloned) // => [1 2 3] [100 2 3]

	// Equal сравнивает два списка поэлементно (обычный знак == для срезов в Go запрещён).
	fmt.Println(slices.Equal([]int{1, 2}, []int{1, 2})) // => true

	// SortFunc — сортировка по своему правилу. Функция возвращает число:
	//   отрицательное — a идёт раньше b; положительное — позже; 0 — равны.
	// Здесь сортируем строки по ДЛИНЕ.
	names := []string{"Бо", "Александр", "Ян"}
	slices.SortFunc(names, func(a, b string) int {
		return len(a) - len(b) // короче -> раньше
	})
	fmt.Println(names) // => [Бо Ян Александр]
}

