/*
Пакет log — печать служебных сообщений (логов).

Чем отличается от fmt.Println? log автоматически добавляет к каждой строке дату и время,
а ещё умеет в одну команду напечатать сообщение И завершить программу (log.Fatal).
По умолчанию log пишет в «поток ошибок» (stderr), а не в обычный вывод.

Зачем нужно: видеть, что и когда происходило в программе (запустилась, что-то посчитала, упала).

Как запустить:  go run main.go
*/
package main

import (
	"log"
	"os"
)

func main() {
	// SetFlags настраивает, какие пометки добавлять к каждой строке.
	// Ldate — дата, Ltime — время, Lshortfile — имя файла и номер строки (помогает искать источник лога).
	log.SetFlags(log.Ldate | log.Ltime | log.Lshortfile)

	// SetPrefix добавляет одинаковую приставку ко всем строкам — удобно отличать свои логи.
	log.SetPrefix("[app] ")

	// Print / Printf / Println — как у fmt, но с датой/временем впереди.
	log.Println("программа запустилась")
	// => [app] 2026/05/25 16:00:00 main.go:NN: программа запустилась

	count := 42
	log.Printf("обработано записей: %d", count) // => [app] ... обработано записей: 42
	log.Print("ещё одно сообщение")             // Print — без переноса/формата

	// SetOutput меняет, КУДА идут логи. По умолчанию — stderr; направим в обычный вывод (stdout).
	log.SetOutput(os.Stdout)
	log.Println("теперь пишем в stdout")

	// log.Fatal = напечатать сообщение И сразу завершить программу с кодом ошибки (1).
	// Используют только когда продолжать НЕЛЬЗЯ (например, не удалось подключиться к базе).
	// Здесь закомментировано, чтобы программа доработала до конца.
	//
	// log.Fatal("не удалось подключиться к базе — выходим")

	log.Println("программа завершилась")
}

/*
Что важно запомнить:
  • log.Println/Printf/Print — как fmt, но с датой и временем. Для служебных сообщений берут log.
  • log.Fatal/Fatalf = напечатать + завершить программу (код выхода 1). Только для «дальше работать нельзя».
  • SetFlags — настроить пометки (дата/время/файл), SetPrefix — приставку, SetOutput — куда писать.
  • Lshortfile добавляет «файл:строка» — экономит время при поиске, где сработал лог.

Чем будешь пользоваться позже:
  • log/slog — «структурные» логи (пары ключ=значение, удобно для серверов). Это уровень production.

Маленькая задача:
  1) Включи только время: log.SetFlags(log.Ltime). Напечатай два сообщения и посмотри на формат.
*/
