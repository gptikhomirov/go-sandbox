/*
Пакет encoding/hex — кодирование байтов в шестнадцатеричную строку (и обратно).

Hex представляет каждый байт двумя символами 0-9a-f. Зачем: показать хеши/контрольные суммы,
бинарные id, ключи в читаемом виде. Один байт -> ровно 2 hex-символа (предсказуемая длина).

Hex vs base64: hex длиннее (в 2 раза от байт), зато читается «по парам» и привычен для хешей/дампов.
base64 компактнее — для больших данных и токенов.

Как запустить:  go run main.go
*/
package main

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
)

func main() {
	// EncodeToString — байты -> hex-строка. Классика: показать хеш.
	sum := sha256.Sum256([]byte("данные"))
	h := hex.EncodeToString(sum[:])
	fmt.Println(len(h)) // => 64 (32 байта * 2 символа)
	fmt.Println(h[:16]) // первые 16 hex-символов

	// DecodeString — hex-строка -> байты (например, прочитать хеш/ключ из конфига).
	raw, err := hex.DecodeString("48656c6c6f")
	if err != nil {
		fmt.Println("кривой hex:", err)
		return
	}
	fmt.Println(string(raw)) // => Hello

	// На нечётной длине или недопустимом символе DecodeString вернёт ошибку.
	_, err = hex.DecodeString("xyz")
	fmt.Println(err != nil) // => true
}

