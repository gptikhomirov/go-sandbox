/*
Пакет unicode/utf8 — работа с UTF-8: правильно считать символы и декодировать руны.

Ключевая идея: в Go len(s) даёт число БАЙТ, а не символов. Для не-латиницы это разные числа
(кириллица — 2 байта на букву, эмодзи — 4). utf8 умеет считать именно символы (руны) и проверять,
что байты вообще являются корректным UTF-8.

Зачем: валидация длины (ника, сообщения) в СИМВОЛАХ, проверка «битых» данных, посимвольный разбор.

Как запустить:  go run main.go
*/
package main

import (
	"fmt"
	"unicode/utf8"
)

func main() {
	s := "привет"

	// len(s) — БАЙТЫ; RuneCountInString — СИМВОЛЫ. Частая ловушка при ограничении длины.
	fmt.Println(len(s))                      // => 12 (байт)
	fmt.Println(utf8.RuneCountInString(s))   // => 6 (символов)

	// ValidString — проверить, что строка является корректным UTF-8 (важно для данных из сети/файлов).
	fmt.Println(utf8.ValidString(s))                  // => true
	fmt.Println(utf8.Valid([]byte{0xff, 0xfe}))       // => false (битые байты)

	// DecodeRuneInString — прочитать ПЕРВУЮ руну и узнать, сколько байт она заняла.
	r, size := utf8.DecodeRuneInString(s)
	fmt.Printf("%c занимает %d байта\n", r, size) // => п занимает 2 байта

	// RuneLen — сколько байт займёт руна в UTF-8.
	fmt.Println(utf8.RuneLen('п'), utf8.RuneLen('a'), utf8.RuneLen('😀')) // => 2 1 4
}

