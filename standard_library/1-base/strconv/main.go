/*
Пакет strconv — превращение строк в числа/логические значения и обратно
("str" = string/строка, "conv" = convert/преобразовать).

Зачем нужно: данные часто приходят в виде ТЕКСТА (ввод пользователя, настройки, файлы),
а считать с ними нельзя, пока не превратишь текст в число. И наоборот — число в текст для вывода.

Важно: эти функции возвращают ДВА значения — результат и ошибку. Ошибка не nil, если текст
нельзя превратить в число (например, "abc" или "12.5" для целого). Её нужно проверять.

Как запустить:  go run main.go
*/
package main

import (
	"fmt"
	"strconv"
)

func main() {
	// Atoi: строка -> int ("ASCII to integer"). Самый частый случай.
	n, err := strconv.Atoi("42")
	if err != nil {
		fmt.Println("это не число:", err)
	}
	fmt.Println(n + 1) // => 43  (теперь это число, с ним можно считать)

	// Если текст плохой — будет ошибка, а результат 0. Поэтому ошибку важно проверять.
	bad, err := strconv.Atoi("abc")
	fmt.Println(bad, err != nil) // => 0 true

	// Itoa: int -> строка ("integer to ASCII"). Обратное к Atoi.
	fmt.Println("номер " + strconv.Itoa(100)) // => номер 100

	// ParseFloat: строка -> дробное число. Второй аргумент 64 — точность (float64).
	price, _ := strconv.ParseFloat("19.99", 64) // _ значит «ошибка нам сейчас не нужна»
	fmt.Printf("%.2f\n", price*2)               // => 39.98

	// ParseBool: строка -> true/false. Понимает "true", "false", "1", "0", "t", "f".
	on, _ := strconv.ParseBool("true")
	fmt.Println(on) // => true

	// FormatFloat: дробное число -> строка с нужным числом знаков.
	// 'f' — обычный вид, 2 — два знака после точки, 64 — точность.
	fmt.Println(strconv.FormatFloat(3.14159, 'f', 2, 64)) // => 3.14

	// ── Ещё функции пакета ──
	// ParseInt: строка -> int64. base=0 — определить систему по префиксу (0x — 16-ричная).
	big, _ := strconv.ParseInt("0xFF", 0, 64)
	fmt.Println(big) // => 255
	// FormatInt: int64 -> строка в нужной системе счисления (2 — двоичная).
	fmt.Println(strconv.FormatInt(10, 2)) // => 1010
}

/*
Что важно запомнить:
  • Текст и число — это РАЗНЫЕ вещи. "42" нельзя складывать как число, пока не превратишь через Atoi.
  • Atoi: строка -> int. Itoa: int -> строка. Запомни пару.
  • Все Parse-функции возвращают (значение, ошибку). При плохом тексте ошибка != nil, а значение 0.
    Всегда проверяй ошибку, иначе получишь «тихий» 0 и непонятный баг.
  • _ на месте ошибки означает «мне сейчас не важно» — но в реальном коде ошибку лучше проверять.

Маленькие задачи:
  1) Преврати "7" и "5" в числа через Atoi и напечатай их сумму (должно быть 12, а не "75").
  2) Попробуй Atoi("3.14") — посмотри, что вернётся в результате и в ошибке.
*/
