/*
Пакет crypto/subtle — сравнение секретов за ПОСТОЯННОЕ время (constant-time).

Проблема: обычное сравнение строк (==) останавливается на первом несовпавшем байте. По времени
ответа атакующий может побайтово подобрать секрет (timing-атака). subtle сравнивает ВСЕГДА за
одинаковое время — без утечки информации через тайминг.

Зачем: сравнивать токены, API-ключи, подписи, пароли-в-виде-хеша — всё, что секретно.

Как запустить:  go run main.go
*/
package main

import (
	"crypto/subtle"
	"fmt"
)

// safeEqual сравнивает два секрета безопасно (для строк одинаковой длины).
func safeEqual(a, b string) bool {
	// ConstantTimeCompare возвращает 1, если равны, и 0 иначе. Время не зависит от того,
	// где именно отличие — поэтому по таймингу нельзя угадать правильные байты.
	return subtle.ConstantTimeCompare([]byte(a), []byte(b)) == 1
}

func main() {
	realToken := "secret-token-abc123"

	fmt.Println(safeEqual(realToken, "secret-token-abc123")) // => true
	fmt.Println(safeEqual(realToken, "secret-token-xxxxxx")) // => false
	fmt.Println(safeEqual(realToken, "короткий"))            // => false (разная длина -> не равны)

	// ВАЖНО: ConstantTimeCompare скрывает, ГДЕ отличие, но НЕ скрывает длину
	// (для разной длины возвращает 0 сразу). Поэтому секреты обычно сравнивают как хеши
	// фиксированной длины (см. crypto/hmac.Equal — он внутри использует именно subtle).
}

